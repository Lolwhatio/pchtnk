import { Extension, InputRule } from '@tiptap/core'
import { isRuleOn } from '../utils/typograf'

// Типографика прямо при наборе: кавычки-ёлочки, тире вместо дефиса,
// многоточие, короткое тире в диапазоне лет. Раньше всё это появлялось
// только по ⌘⇧T, и до нажатия текст выглядел набранным на машинке.
//
// Правила — те же, что у типографа, и слушают те же галочки в настройках
// (utils/typograf): выключил «кавычки-ёлочки» — не подставляются и здесь.
// Остальное (числа, инициалы, сокращения) по-прежнему за кнопкой: там
// правила смотрят на предложение целиком, а не на два последних знака.
//
// Неразрывные пробелы при наборе не ставим — кроме пробела перед тире,
// который принадлежит самому тире. Предлог, приклеенный к слову прямо
// под руками, менял бы вёрстку уже набранного: строка перестроилась бы
// сама. Висячие предлоги — работа типографа, по ⌘⇧T и в выгрузках.

const NBSP = '\u00A0'

export const LiveTypograf = Extension.create({
  name: 'liveTypograf',

  addInputRules() {
    const rule = (find, setting, replace) => new InputRule({
      find,
      handler: ({ state, range, match }) => {
        if (!isRuleOn(setting)) return null
        state.tr.insertText(replace(match), range.from, range.to)
      },
    })

    return [
      // Три точки — многоточие
      rule(/\.\.\.$/, 'common/punctuation/hellip', () => '…'),

      // Кавычки: открывающая — в начале строки, после пробела, скобки
      // или тире, в остальных случаях закрывающая. Вложенные «лапки»
      // расставит ⌘⇧T: на ходу видно только один знак назад
      rule(/(^|[\s([{<«„—–])"$/u, 'common/punctuation/quote', (m) => `${m[1]}«`),
      rule(/"$/, 'common/punctuation/quote', () => '»'),

      // Дефис между словами — это тире. Пробел перед ним неразрывный:
      // тире остаётся на строке предыдущего слова
      rule(/(\S)[ \u00A0]+-[ ]$/u, 'ru/dash/main', (m) => `${m[1]}${NBSP}— `),
      rule(/(\S)--$/u, 'ru/dash/main', (m) => `${m[1]}—`),

      // Диапазон лет — короткое тире: 2017–2018. Только годы, иначе под
      // правило попадут телефоны и номера домов
      rule(/((?:19|20)\d{2})-((?:19|20)\d{2})$/, 'ru/dash/years', (m) => `${m[1]}–${m[2]}`),
    ]
  },
})
