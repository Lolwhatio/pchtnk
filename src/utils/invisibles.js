// Невидимые символы: нулевой ширины, управляющие направлением письма
// и теговые. В тексте их не видно, но они ломают поиск по документу,
// сбивают счётчик знаков и дают неожиданные переносы. Приезжают из веба
// и из вывода нейросетей — не как подпись, а как побочный продукт вёрстки.
//
// Чего здесь намеренно НЕТ:
//
//   U+00A0  неразрывный пробел  — их расставляет типограф после предлогов;
//   U+202F  узкий неразрывный   — типограф ставит перед %, № и единицами.
//
// Это видимые пробелы и часть типографики Печатников. Вычищать их значило бы
// воевать с собственным инструментом: нажал ⌘⇧T, потом «убрать невидимые» —
// и половина работы типографа откатилась.
const INVISIBLE = new RegExp(
  '[\\u00AD\\u180E\\u200B\\u200C\\u2060-\\u2064\\uFEFF]' + // нулевая ширина, мягкий перенос
  '|[\\u200E\\u200F\\u202A-\\u202E\\u2066-\\u2069]' +      // управление направлением письма
  '|[\\u{E0000}-\\u{E007F}]',                              // теговые символы
  'gu'
)

// U+200D склеивает эмодзи: 👨‍👩‍👧 — это три картинки и две склейки,
// без них семья распадается на трёх человек подряд. Поэтому между
// картинками склейку оставляем, а одиночную — убираем.
// Селектор начертания U+FE0F учитываем отдельно: в ❤️‍🔥 он стоит
// прямо перед склейкой, и без него проверка «слева картинка» не срабатывает.
// Сами символы пишем escape-последовательностями, а не литералами: файл
// о невидимках, набранный невидимками, нечитаем и правится вслепую.
const PICT_BEFORE = /\p{Extended_Pictographic}\uFE0F?$/u
const PICT_AFTER  = /^\p{Extended_Pictographic}/u
const JOINER      = /\u200D/gu

function isEmojiJoiner(text, i) {
  return PICT_BEFORE.test(text.slice(Math.max(0, i - 4), i)) &&
         PICT_AFTER.test(text.slice(i + 1))
}

// Возвращает очищенную строку и число выброшенных символов.
// Считаем совпадения, а не разницу длин: теговые символы занимают
// две единицы UTF-16, и по длине счёт вышел бы вдвое больше.
export function stripInvisibles(text) {
  let removed = 0

  let out = text.replace(INVISIBLE, () => { removed++; return '' })

  out = out.replace(JOINER, (m, i, whole) => {
    if (isEmojiJoiner(whole, i)) return m
    removed++
    return ''
  })

  return { text: out, removed }
}

export function pluralInvisible(n) {
  const m10 = n % 10, m100 = n % 100
  if (m10 === 1 && m100 !== 11)                            return 'невидимый символ'
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20))   return 'невидимых символа'
  return 'невидимых символов'
}
